export type Dict = (typeof dict)[Lang];

type I18nCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Dict;
};

const Ctx = createContext<I18nCtx | null>(null);

const STORAGE_KEY = "pra-lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved === "en" || saved === "es") {
        setLangState(saved);
        return;
      }
      const nav = navigator.language?.toLowerCase() ?? "";
      if (nav.startsWith("es")) setLangState("es");
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo(
    () => ({ lang, setLang, t: dict[lang] }),
    [lang, setLang],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function trendLabelKey(
  label: "alcista" | "bajista" | "lateral",
  t: Dict,
): string {
  if (label === "alcista") return t.trendBull;
  if (label === "bajista") return t.trendBear;
  return t.trendSide;
}
